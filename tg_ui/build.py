"""Regenerates the design assets derived from Python data:

    static/css/categories.css   - category colour tokens + badge classes
    static/img/plants/*.svg     - every flower at every growth stage

Run `python -m tg_ui.build` after editing categories.py or flowers.py and
commit the output; tests/test_tg_ui.py fails if the files are stale.
"""

import os

from tg_ui import STATIC_DIR, categories, flowers

CSS_PATH = os.path.join(STATIC_DIR, 'css', 'categories.css')
PLANT_DIR = os.path.join(STATIC_DIR, 'img', 'plants')


def categories_css():
    light, dark, classes = [], [], []
    for c in categories.CATEGORIES:
        s = c['slug']
        light.append(
            f"    --category-{s}: {c['background']};\n"
            f"    --category-{s}-border: {c['border']};\n"
            f"    --category-{s}-soft-bg: {c['light']['soft_bg']};\n"
            f"    --category-{s}-soft-text: {c['light']['soft_text']};\n")
        dark.append(
            f"    --category-{s}: {c['dark']['hue']};\n"
            f"    --category-{s}-border: {c['dark']['hue']};\n"
            f"    --category-{s}-soft-bg: {c['dark']['soft_bg']};\n"
            f"    --category-{s}-soft-text: {c['dark']['soft_text']};\n")
        classes.append(
            f".badge-category-{s}, .tg-hue-{s} {{ --cat-hue: var(--category-{s}); --cat-bg: var(--category-{s}-soft-bg);"
            f" --cat-text: var(--category-{s}-soft-text); }}\n")
    classes.append(
        f".badge-category-{categories.NONE_SLUG}, .tg-hue-{categories.NONE_SLUG} {{ --cat-hue: var(--text-muted); --cat-bg: var(--neutral-soft-bg);"
        " --cat-text: var(--neutral-soft-text); }\n")
    return (
        "/* GENERATED by tg_ui/build.py from tg_ui/categories.py - do not edit by hand.\n"
        "   Category palette: the garden hue, ring and badge surface/text of every\n"
        "   branded category, light and dark. Deliberately separate from the\n"
        "   semantic success/warning/danger tokens. */\n\n"
        ":root {\n" + "\n".join(light) + "}\n\n"
        "[data-bs-theme=\"dark\"] {\n" + "\n".join(dark) + "}\n\n"
        + "".join(classes)
    )


def plant_files():
    """{filename: svg} for every flower x stage."""
    return {
        f'{flower}-{stage}.svg': flowers.plant_svg(flower, stage)
        for flower in flowers.FLOWERS for stage in flowers.STAGES
    }


def build():
    os.makedirs(PLANT_DIR, exist_ok=True)
    with open(CSS_PATH, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(categories_css())
    for name, svg in plant_files().items():
        with open(os.path.join(PLANT_DIR, name), 'w', encoding='utf-8', newline='\n') as fh:
            fh.write(svg)


if __name__ == '__main__':
    build()
    print(f'wrote {CSS_PATH} and {len(plant_files())} plants')
